export const LOCALES: Record<string, Record<string, string>> = { en, pl };

export const language = (hass?: HomeAssistant): string =>
  (hass?.locale?.language ?? hass?.language ?? "en").split("-")[0];

export const t = (
  hass: HomeAssistant | undefined,
  key: StringKey,
  vars?: Record<string, string | number>,
): string => {
  let text = LOCALES[language(hass)]?.[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(vars ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
};

export type PluralKey = "orders" | "items" | "pieces" | "hidden" | "unread" | "invoices";

/** Plural forms keyed `<key>.<Intl.PluralRules category>` (Polish uses one/few/many/other). */
export const plural = (hass: HomeAssistant | undefined, key: PluralKey, n: number): string => {
  const category = new Intl.PluralRules(language(hass)).select(n);
  const form = (["one", "few", "many"].includes(category) ? category : "other") as
    | "one"
    | "few"
    | "many"
    | "other";
  return t(hass, `${key}.${form}`, { n });
};

/** A status label: translated when known, humanised otherwise. */
export const statusLabel = (
  hass: HomeAssistant | undefined,
  status: string,
  humanize: (status: string) => string,
): string => {
  const key = `status_${status}` as StringKey;
  return key in en ? t(hass, key) : humanize(status);
};
